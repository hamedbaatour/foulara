import {readFile, writeFile, mkdir, rm, cp} from 'node:fs/promises';
import {createHash} from 'node:crypto';

// The editable storefront remains a single file. Deployment extracts cacheable media.
let markup = await readFile(new URL('../the-vintage-garden/index.html', import.meta.url), 'utf8');
const root = new URL('../dist/', import.meta.url);
await rm(root, {recursive: true, force: true});
await mkdir(new URL('assets/', root), {recursive: true});
await mkdir(new URL('../generated/', import.meta.url), {recursive: true});
const pending = [];
function asset(name, encoded, extension) {
  const bytes = Buffer.from(encoded, 'base64');
  const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const file = `${name}.${digest}.${extension}`;
  pending.push(writeFile(new URL(`assets/${file}`, root), bytes));
  return `/assets/${file}`;
}
const pattern = /(<script type="application\/json" id="product-assets">)([\s\S]*?)(<\/script>)/;
const match = markup.match(pattern);
if (!match) throw new Error('Missing product assets');
const images = JSON.parse(match[2]);
for (const [name, data] of Object.entries(images)) {
  const image = data.match(/^data:image\/(webp|avif);base64,(.+)$/);
  if (image) images[name] = asset(name, image[2], image[1]);
}
markup = markup.replace(pattern, () => match[1] + JSON.stringify(images) + match[3]);
let fontIndex = 0;
markup = markup.replace(/data:font\/woff2;base64,([A-Za-z0-9+/=]+)/g, (_, data) => asset(`font-${++fontIndex}`, data, 'woff2'));
const fonts = {normal: [], arabic: [], italic: []};
for (const face of markup.matchAll(/@font-face\s*\{[^}]*\}/g)) {
  const url = face[0].match(/url\((\/assets\/[^)]+)\)/)?.[1];
  if (!url) continue;
  if (/Manrope|Cormorant Garamond/.test(face[0])) {
    fonts.normal.push(url);
    if (face[0].includes('Cormorant Garamond')) {
      if (face[0].includes('font-style: normal')) fonts.arabic.push(url);
      if (face[0].includes('font-style: italic')) fonts.italic.push(url);
    }
  } else if (/Noto Sans Arabic/.test(face[0]) && /U\+0600-|U\+0000-00FF/.test(face[0])) fonts.arabic.push(url);
}
markup = markup.replace('</head>', '<script>window.__FOULARA_SERVER__=true;</script></head>');
if (/data:(image\/(webp|avif)|font\/woff2);base64,/.test(markup)) throw new Error('Unextracted asset');
await Promise.all(pending);
await writeFile(new URL('index.html', root), markup);
await writeFile(new URL('_headers', root), `/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n  X-Content-Type-Options: nosniff\n`);
await writeFile(new URL('../generated/site-data.json', import.meta.url), JSON.stringify({images, fonts}));
// A checked-in static mirror also supports the existing Pages project, which
// publishes the repository root. There is still only one editable storefront.
const publicOrigin = (process.env.SITE_ORIGIN || 'https://foulara.pages.dev').replace(/\/$/, '');
const hero = 'DSC04216';
const srcset = [480, 768, 960, 1440].map(width => `${images[`${hero}-${width}`]} ${width}w`).join(', ');
const preloads = fonts.normal.map(url => `<link rel="preload" as="font" type="font/woff2" crossorigin href="${url}">`).join('')
  + `<link rel="preload" as="image" fetchpriority="high" href="${images[`${hero}-960`]}" imagesrcset="${srcset}" imagesizes="(max-width: 760px) calc(100vw - 36px), (max-width: 1100px) 48vw, 55vw">`;
const staticMarkup = markup.replace('</head>', `<!-- Generated by scripts/build.mjs. Edit the-vintage-garden/index.html. -->${preloads}<link rel="canonical" href="${publicOrigin}/"></head>`);
await cp(new URL('assets/', root), new URL('../assets/', import.meta.url), {recursive: true});
await writeFile(new URL('../index.html', import.meta.url), staticMarkup);
const redirects = '/the-vintage-garden/ /product/the-vintage-garden-greige 308\n/the-vintage-garden/index.html /product/the-vintage-garden-greige 308\n' + ['/shop', '/collections', '/story', '/contact', '/help', '/privacy', '/saved', '/checkout', '/confirmation', '/product/*'].map(path => `${path} / 200`).join('\n') + '\n';
await writeFile(new URL('../_redirects', import.meta.url), redirects);
await writeFile(new URL('_redirects', root), redirects);
await writeFile(new URL('../_headers', import.meta.url), `/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: same-origin\n/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n`);
await writeFile(new URL('../404.html', import.meta.url), '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>FOULARA</title><h1>Page not found</h1><a href="/">Return to FOULARA</a></html>');
await writeFile(new URL('../robots.txt', import.meta.url), `User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /checkout\nDisallow: /saved\nDisallow: /confirmation\nSitemap: ${publicOrigin}/sitemap.xml\n`);
const pages = ['/', '/shop', '/collections', '/story', '/contact', '/help', '/privacy', ...['the-vintage-garden-greige', 'the-vintage-garden-royal-blue', 'rosette-yellow', 'shadha-beige'].map(id => '/product/' + id)];
const sitemap = '<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + pages.flatMap(path => ['en', 'fr', 'ar'].map(lang => `<url><loc>${publicOrigin}${path}${lang === 'en' ? '' : '?lang=' + lang}</loc></url>`)).join('') + '</urlset>';
await writeFile(new URL('../sitemap.xml', import.meta.url), sitemap);
console.log(`Built ${pending.length} cacheable assets and ${(Buffer.byteLength(markup) / 1024).toFixed(1)} KB storefront HTML.`);
